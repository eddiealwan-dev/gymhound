import type { Program, ProgramDay, ProgramSlot, ProgramSource } from '../seed/programTypes';

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function slot(dayId: string, [catalogName, sets, repMin, repMax]: [string, number, number, number], index: number): ProgramSlot {
  const exerciseId = slug(catalogName);
  return {
    id: `${dayId}:${exerciseId}`,
    exerciseId,
    catalogName,
    note: '',
    sets,
    repMin,
    repMax,
    targetUnit: 'reps',
    ruleKind: 'load',
    incrementLb: 5,
    halveAfterFirstMiss: true,
    resetMultiplier: 0.9,
    sessionsToRaise: 1,
    ladder: null,
    addSet: null,
    weekly: null,
    metcon: null,
    manualText: null,
    countsTowardVolume: true,
    credits: [],
    creditPerSet: 1,
    deloadExempt: false,
    isMain: index === 0,
    warmUpLine: index === 0,
  };
}

function day(programId: string, daySlug: string, name: string, slots: [string, number, number, number][]): ProgramDay {
  const dayId = `${programId}:${daySlug}`;
  return { slug: daySlug, name, slots: slots.map((s, i) => slot(dayId, s, i)) };
}

type Shown = Pick<
  Program,
  | 'id'
  | 'jsonId'
  | 'number'
  | 'name'
  | 'level'
  | 'goal'
  | 'daysPerWeek'
  | 'weeks'
  | 'equipment'
  | 'free'
  | 'schedule'
  | 'specialWeeksText'
  | 'lineage'
  | 'whyItWorks'
  | 'progressionNotes'
  | 'afterThisProgram'
  | 'sourceIds'
  | 'picture'
  | 'days'
>;

function program(p: Shown): Program {
  return {
    ...p,
    volumeChecked: true,
    volumeBandExempt: [],
    expectedVolume: {},
    expectedDelts: { side: 0, rear: 0, front: 0 },
    weekPlan: [],
    missesToReset: p.level === 'Beginner' ? 3 : 2,
    reactiveDeload: p.number === 11,
  };
}

