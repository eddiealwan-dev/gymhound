// Builds GymHound's twenty programs from the owner's Program Library v2 (spec §18.29, R596). Run it from the project
// root:  npm run build:programs
//
// It reads the vendored scripts/vendor/programs/gymhound_programs.json and why-bullets.json (the docx's "Why it works"
// bullets), maps them with src/seed/programMapping.ts against the exercise library and the new exercises (all imported
// straight into Node 24, which strips the types), and writes the only copy of src/seed/programs.generated.ts. The
// mapping throws, naming the entry, on anything it can't place (an unknown catalog name, an exercise id the library
// lacks, a custom rule without a transcription, bullets that don't join into the paragraph), and then nothing is
// written. Never edit the generated file by hand.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LIBRARY_EXERCISES } from '../src/seed/library.generated.ts';
import { CATALOG_NEW, NEW_ALIASES, RUNG_NEW } from '../src/seed/newExerciseData.ts';
import { buildPrograms, FREE_NUMBERS, programLibrary } from '../src/seed/programMapping.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = join(ROOT, 'scripts', 'vendor', 'programs');
const OUT = join(ROOT, 'src', 'seed', 'programs.generated.ts');

const HEADER = [
  '// Generated by scripts/build-programs.mjs from scripts/vendor/programs/gymhound_programs.json (spec §18.29).',
  '// Do not edit: change src/seed/programMapping.ts or the vendored JSON and run `npm run build:programs`.',
];

const json = JSON.parse(readFileSync(join(VENDOR, 'gymhound_programs.json'), 'utf8'));
const why = JSON.parse(readFileSync(join(VENDOR, 'why-bullets.json'), 'utf8'));
const library = programLibrary(LIBRARY_EXERCISES, [...CATALOG_NEW, ...RUNG_NEW], NEW_ALIASES);
const { programs, sources } = buildPrograms(json, library, why);

// Free's five in the owner's order, then the Pro programs by number (R597).
const free = FREE_NUMBERS.map((n) => programs.find((p) => p.number === n));
const order = [...free, ...programs.filter((p) => !p.free).sort((a, b) => a.number - b.number)].map((p) => p.id);
if (free.some((p) => p === undefined || !p.free) || new Set(order).size !== programs.length) {
  throw new Error('The program order must list every program once, the free five first');
}

// One program field per line and one slot per line, so a change to the JSON or the mapping reads as a small diff.
function programText(p) {
  const lines = ['  {'];
  for (const [key, value] of Object.entries(p)) {
    if (key === 'days') continue;
    lines.push(`    ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  }
  lines.push('    "days": [');
  for (const day of p.days) {
    lines.push(`      { "slug": ${JSON.stringify(day.slug)}, "name": ${JSON.stringify(day.name)}, "slots": [`);
    for (const slot of day.slots) lines.push(`        ${JSON.stringify(slot)},`);
    lines.push('      ] },');
  }
  lines.push('    ],');
  lines.push('  },');
  return lines.join('\n');
}

const text = [
  ...HEADER,
  "import type { Program, ProgramSource } from './programTypes';",
  '',
  '/** The twenty programs (R596), by program number. */',
  'export const PROGRAMS: readonly Program[] = [',
  ...programs.map(programText),
  '];',
  '',
  `/** Every bundled source (R631), by id (${sources.length}). */`,
  'export const PROGRAM_SOURCES: readonly ProgramSource[] = [',
  ...sources.map((s) => `  ${JSON.stringify(s)},`),
  '];',
  '',
  '/** Program ids in the order Routines lists them: the free five first (R597), then Pro by number. */',
  'export const PROGRAM_ORDER: readonly string[] = [',
  ...order.map((id) => `  ${JSON.stringify(id)},`),
  '];',
  '',
  'export function programById(id: string): Program | undefined {',
  '  return PROGRAMS.find((p) => p.id === id);',
  '}',
  '',
].join('\n');
writeFileSync(OUT, text);

const slots = programs.reduce((n, p) => n + p.days.reduce((m, d) => m + d.slots.length, 0), 0);
console.log(`${programs.length} programs (${programs.filter((p) => p.free).length} free), ${slots} slots, ${sources.length} sources.`);
